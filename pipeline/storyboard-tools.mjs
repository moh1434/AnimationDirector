// Helpers for whoever directs a storyboard (a person, Claude, or a small local model):
//   brief(dir)    → build/brief.md: the narration with word times, pauses, cut points and every valid name
//   validate(sb)  → precise errors ("scene s3, props[1].name …") with a suggested fix for each
// Neither one limits what a storyboard may do; they only catch mistakes early.
import { SCALE, bgType, clipSceneWords, clipTime, humanLimit, isAnimal, isClipRef, storyProblems } from "../remotion/story/story-mode.mjs";
import { dialogueStale, loadTimeline } from "./dialogue.mjs";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { catalog, catalogText } from "./catalog.mjs";
import { norm, propHits } from "./lexicon.mjs";
import { videoDuration } from "./compile.mjs";

const fmt = (t) => (Math.round(t * 100) / 100).toFixed(2);

/* ------------------------------ brief ------------------------------ */
export function writeBrief(dir, { analysis, segments, settings, storyboard }) {
  const c = catalog();
  const words = analysis.words ?? [];
  const timeline = loadTimeline(dir);
  const lines = [];
  lines.push(`# Director brief — ${storyboard?.title ?? settings?.title ?? ""}`, "");
  lines.push(`Voice: ${fmt(analysis.duration)} s (video: ${fmt(videoDuration(storyboard ?? {}, analysis))} s; never shorter than the voice, longer with the storyboard's "endHold" or "duration") · language: ${storyboard?.language ?? settings?.language ?? "auto"} · ${settings?.fps ?? 60} fps · renders: ${(settings?.formats ?? ["shorts"]).join(", ")}`);
  lines.push("Generated by the pipeline. Everything you need to write storyboard.json is in this file.", "");
  lines.push("## Narration, segment by segment", "");
  lines.push("Each word is `word@seconds`. Use `\"at\": \"@word\"` (the first word in the scene that starts with that text) to make something appear when it is said.", "");
  if (timeline) lines.push("This is a multi-voice story. Use `\"start\": \"clip:12\"` for a scene and `\"at\": \"clip:12\"` (also `clip:12:end`, `clip:12+0.4`) for anything inside one: these follow the recordings, so the storyboard survives new takes.", "");
  segments.forEach((s, i) => {
    // words carry the segment they were matched to; fall back to time ranges
    const ws = words.some((w) => w.seg !== undefined) ? words.filter((w) => w.seg === i) : words.filter((w) => w.s >= s.start - 0.02 && w.s < s.end - 0.02);
    const a = ws[0]?.s ?? s.start, b = ws.length ? ws[ws.length - 1].e : s.end;
    const clip = timeline?.[i];
    lines.push(clip ? `### Clip ${clip.clip} · ${clip.who} · spoken ${fmt(a)}–${fmt(b)} s` : `### Segment ${i + 1} · spoken ${fmt(a)}–${fmt(b)} s`);
    lines.push(`"${s.text}"`);
    lines.push(ws.map((w) => `${w.w}@${fmt(w.s)}`).join("  ") || "(no words found)", "");
  });
  // good cut points: just before a word that starts a sentence or follows a pause
  const voiced = analysis.voiced ?? [];
  const pauses = [];
  for (let i = 1; i < voiced.length; i++) if (voiced[i][0] - voiced[i - 1][1] >= 0.25) pauses.push([voiced[i - 1][1], voiced[i][0]]);
  lines.push("## Pauses in the voice", "");
  lines.push(pauses.length ? pauses.map(([a, b]) => `${fmt(a)}–${fmt(b)} s`).join(" · ") : "(none longer than 0.25 s)", "");
  const cuts = [];
  words.forEach((w, i) => {
    const prev = words[i - 1];
    if (!prev) return;
    const sentence = /[.!?؟…]$/.test(prev.w);
    const pause = pauses.some(([a, b]) => w.s >= a && w.s <= b + 0.15) && (w.seg === undefined || w.seg !== prev.seg);
    if (sentence || pause) cuts.push(`${fmt(Math.max(0, w.s - 0.06))} (before “${w.w}”)`);
  });
  lines.push("## Good scene start times", "");
  lines.push("A scene should start just before a word, never in the middle of one. These are before a new sentence or after a pause:", "");
  lines.push(cuts.join(" · ") || "(use the segment starts)", "");
  lines.push("## Visual story plan (complete before editing the storyboard)", "");
  lines.push("Read REFERENCE_VIDEO_STUDY.md for the five-reference study. Copy this worksheet to build/direction-notes.md before filling it in; this generated brief is replaced on the next plan/brief run.", "");
  lines.push("Choose a visual treatment for each passage: character action, mechanism/process, or spatial context. These are planning notes, not new storyboard fields or layout names.", "");
  lines.push("| Segment | Viewer takeaway | Visible cause → change → result | Focal subject / retained setting | Spoken trigger | Asset needed |", "|---|---|---|---|---|---|");
  segments.forEach((s, i) => lines.push(`| ${i + 1} (${fmt(s.start)}–${fmt(s.end)} s) | | | | | |`));
  lines.push("", "- Open with the subject or situation implied by the existing narration. Do not add a greeting or rewrite the voice.",
    "- Keep a setting, subject and screen direction while explaining one process; repeat a layout when continuity helps. Change the picture when the meaning changes, not to meet a variation quota.",
    "- Show the verb or consequence, not only a named prop. Plan setup, change and a readable result; use existing actions, props/items, at/out and supported layouts.",
    "- A mechanism can carry the picture without a visible host. Use speaker: none for an off-screen narrator; this does not remove narration audio.",
    "- Use one focal change at a time. Reactions follow the event; camera movement needs a purpose. A deliberate hold is valid.",
    "- Keep captions readable in their reserved band; diagram labels name parts or values instead of duplicating the sentence. Preserve Arabic shaping and reading order.",
    "- Check the opening, cause, result and transition frames, then watch the sequence at playback speed. Geometry checks alone cannot judge whether it explains the line.", "");
  if (storyboard?.scenes?.length) {
    lines.push("## Current storyboard.json", "");
    lines.push("| # | id | start–end | layout | text |", "|---|---|---|---|---|");
    storyboard.scenes.forEach((s, i) => lines.push(`| ${i + 1} | ${s.id ?? ""} | ${typeof s.start === "number" ? fmt(s.start) : s.start}–${typeof s.end === "number" ? fmt(s.end) : s.end ?? ""} | ${s.layout ?? "host_talk"} | ${(s.text ?? "").replace(/\|/g, "/")} |`));
    lines.push("");
  }
  const cast = Object.entries(storyboard?.cast ?? { host: { preset: "host" } }).map(([id, v]) => `${id} (${isAnimal(v) ? v.kind : v.preset ?? id})`).join(", ");
  lines.push("## Cast in this project", "", cast, "");
  lines.push("## Valid names (anything else is an error)", "", "```", catalogText(c), "```", "");
  lines.push("Next: write storyboard.json, then run `pnpm video validate <name>` and fix every error it lists.", "");
  const path = join(dir, "build", "brief.md");
  writeFileSync(path, lines.join("\n"), "utf8");
  return path;
}

/* ----------------------------- validate ----------------------------- */
const lev = (a, b) => {
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++) d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return d[a.length][b.length];
};
const closest = (name, pool, n = 3) => {
  const q = String(name ?? "").toLowerCase().replace(/[\s-]+/g, "_");
  return pool
    .map((p) => ({ p, s: p.includes(q) || q.includes(p) ? 0 : lev(q, p) / Math.max(q.length, p.length) }))
    .sort((a, b) => a.s - b.s).filter((x) => x.s < 0.6).slice(0, n).map((x) => x.p);
};
const hint = (name, pool) => { const c = closest(name, pool); return c.length ? ` Did you mean: ${c.join(", ")}?` : ""; };
/** Suggestions for a missing drawing: narration keywords, aliases, then spelling. */
const propHint = (name, c, custom) => {
  const words = String(name ?? "").toLowerCase().split(/[\s_\-]+/).filter(Boolean);
  const out = [];
  try { for (const h of propHits(words)) if (!out.includes(h.key) && c.props.includes(h.key)) out.push(h.key); } catch {}
  const q = words.join("_");
  for (const [k, al] of Object.entries(c.propAliases)) if (al.some((a) => a.includes(q) || (q.length > 3 && q.includes(a)))) if (!out.includes(k)) out.push(k);
  for (const k of closest(name, [...c.props, ...Object.keys(custom)], 4)) if (!out.includes(k)) out.push(k);
  return out.length ? ` Did you mean: ${out.slice(0, 4).join(", ")}?` : "";
};

/**
 * Check a storyboard against what the renderer supports. Returns { errors, warnings }.
 * Errors would break or silently spoil the render; warnings are judgement calls.
 */
export function validateStoryboard(sb, { words = [], voiced = [], duration, projectDir, customProps = {} } = {}) {
  const c = catalog();
  const errors = [], warnings = [];
  const E = (where, msg) => errors.push(`${where}: ${msg}`);
  const W = (where, msg) => warnings.push(`${where}: ${msg}`);
  const isProp = (n) => !!n && (!!c.resolveProp(n) || String(n).toLowerCase().replace(/\.svg$/, "").replace(/^(file:|props\/)/, "").replace(/[\s-]+/g, "_") in customProps);
  const propPool = [...c.props, ...Object.keys(customProps)];
  /** A costume name with no drawing would silently render nothing, so it is an error. */
  const checkLook = (look, where) => {
    for (const [key, names] of Object.entries(c.looks)) {
      const value = look?.[key];
      if (value && value !== "none" && !names.includes(value)) E(`${where}.${key}`, `"${value}" has no drawing.${hint(value, names)}`);
    }
  };
  const poseProblem = (who, pose) => {
    const pool = isAnimal(sb.cast?.[who]) ? c.animalPoses : c.poses;
    return pool.includes(pose) ? null : `pose "${pose}" does not exist for ${who}.${hint(pose, pool)}`;
  };
  const secondsOf = (start) => (typeof start === "number" ? start : isClipRef(start) ? clipTime(start, sb.dialogue) : null);
  if (!sb || typeof sb !== "object") return { errors: ["storyboard.json is not a JSON object"], warnings };
  if (!Array.isArray(sb.scenes) || !sb.scenes.length) return { errors: ["`scenes` must be a non-empty list"], warnings };
  for (const problem of storyProblems(sb)) errors.push(problem);
  const cast = sb.cast ?? {};
  for (const [id, m] of Object.entries(cast)) {
    checkLook(m?.look, `cast.${id}.look`);
    if (m.kind && m.kind !== "human") continue; // animals are drawn from their kind; a wrong kind is reported above
    const pre = m?.preset ?? id;
    if (!c.presets.includes(pre) && !c.presetAliases[String(pre).toLowerCase()]) E(`cast.${id}`, `preset "${pre}" does not exist.${hint(pre, c.presets)}`);
  }
  const castIds = new Set(["host", ...Object.keys(cast)]);
  let prevStart = -1;
  const isAt = (at, sceneWords, where) => {
    if (at === undefined || at === null || typeof at === "number") return;
    const s = String(at).trim();
    if (/^[+-]?\d+(\.\d+)?$/.test(s) || /^w:\d+$/i.test(s)) return;
    if (isClipRef(s)) {
      if (clipTime(s, sb.dialogue) === null) E(where, `"${s}" does not match a recording (this project has ${sb.dialogue?.length ?? 0}). clip: times need dialogue.json.`);
      return;
    }
    if (!s.startsWith("@")) return E(where, `"${s}" is not a time. Use seconds from the scene start (1.2), "@word", "w:3" or "clip:12".`);
    const q = norm(s.slice(1));
    if (!sceneWords.length) return;
    if (!sceneWords.some((w) => norm(w.w).startsWith(q) || norm(w.w).includes(q)))
      E(where, `"${s}" is not spoken in this scene (it would fall back to 0.3 s). Words here: ${sceneWords.slice(0, 14).map((w) => w.w).join(" ")}${sceneWords.length > 14 ? " …" : ""}`);
  };
  sb.scenes.forEach((s, i) => {
    const at = `scene ${s.id ?? i + 1} (#${i + 1})`;
    const wordStart = /^w:\d+$/i.test(String(s.start ?? ""));
    const start = isClipRef(s.start) ? Math.max(0, (clipTime(s.start, sb.dialogue) ?? NaN) - 0.05) : typeof s.start === "number" ? s.start : wordStart ? (words[+String(s.start).slice(2)]?.s ?? (words.length ? NaN : prevStart + 0.01)) : NaN;
    if (!Number.isFinite(start)) E(at, `start must be a number of seconds, "w:<word index>" or "clip:<recording number>", got ${JSON.stringify(s.start)}`);
    else {
      if (start <= prevStart) E(at, `starts at ${fmt(start)} s, not after the previous scene (${fmt(prevStart)} s). Scenes must be in time order.`);
      if (duration && start >= duration) E(at, `starts at ${fmt(start)} s, after the video ends (${fmt(duration)} s). For a beat after the last word, set the storyboard's "duration" (or "endHold") longer.`);
      // word end times run on through pauses, so only a cut while the voice is actually sounding counts
      const sounding = voiced.some(([a, b]) => start > a + 0.04 && start < b - 0.04);
      const inWord = sounding && words.find((w) => start > w.s + 0.08 && start < w.e - 0.08);
      if (inWord) W(at, `starts in the middle of the word “${inWord.w}” (${fmt(inWord.s)}–${fmt(inWord.e)} s). Start just before a word instead.`);
      prevStart = start;
    }
    if (i === 0 && Number.isFinite(start) && start > 0.05) W(at, "the first scene should start at 0.");
    const next = sb.scenes[i + 1];
    const end = secondsOf(next?.start) ?? duration ?? start + 5;
    const sceneWords = clipSceneWords(words, s, next, i, sb.dialogue) ?? (Number.isFinite(start) ? words.filter((w) => w.s >= start - 0.02 && w.s < end) : []);
    const layout = s.layout ?? "host_talk";
    if (!c.layouts.includes(layout)) E(at, `layout "${layout}" does not exist.${hint(layout, c.layouts)}`);
    // background
    if (typeof s.bg === "string") {
      if (!c.bgColors.includes(s.bg) && !c.bgTypes.includes(s.bg) && !/^#[0-9a-f]{3,8}$/i.test(s.bg)) E(`${at}, bg`, `"${s.bg}" is not a colour name, hex colour or background type.${hint(s.bg, [...c.bgColors, ...c.bgTypes])}`);
    } else if (s.bg && typeof s.bg === "object") {
      if (s.bg.type && !c.bgTypes.includes(s.bg.type)) E(`${at}, bg.type`, `"${s.bg.type}" does not exist.${hint(s.bg.type, c.bgTypes)}`);
      if (s.bg.type === "image" && s.bg.image && projectDir && !/^https?:/.test(s.bg.image) && !existsSync(join(projectDir, s.bg.image))) E(`${at}, bg.image`, `file "${s.bg.image}" is not in the project folder.`);
    }
    if (s.transition && !c.transitions.includes(s.transition)) E(`${at}, transition`, `"${s.transition}" does not exist.${hint(s.transition, c.transitions)}`);
    // characters
    const chars = s.characters ?? [];
    chars.forEach((ch, j) => {
      const w = `${at}, characters[${j}]`;
      if (!ch.who) E(w, `needs "who" (a cast id: ${[...castIds].join(", ")})`);
      else if (!castIds.has(ch.who)) E(w, `who "${ch.who}" is not in "cast". Add it to cast (e.g. "${ch.who}": {"preset": "${closest(ch.who, c.presets, 1)[0] ?? "student"}"}) or use: ${[...castIds].join(", ")}.`);
      if (ch.pose && poseProblem(ch.who, ch.pose)) E(w, poseProblem(ch.who, ch.pose));
      checkLook(ch.look, `${w}.look`);
      (ch.move ?? []).forEach((m, k) => { isAt(m.at, sceneWords, `${w}.move[${k}].at`); isAt(m.until, sceneWords, `${w}.move[${k}].until`); });
      if (ch.expression && !c.expressions.includes(ch.expression)) E(w, `expression "${ch.expression}" does not exist.${hint(ch.expression, c.expressions)}`);
      if (ch.emote && !c.emotes.includes(ch.emote)) E(w, `emote "${ch.emote}" does not exist.${hint(ch.emote, c.emotes)}`);
      if (ch.enter && !c.enters.includes(ch.enter)) E(w, `enter "${ch.enter}" does not exist.${hint(ch.enter, c.enters)}`);
      if (ch.holding && !isProp(ch.holding)) E(w, `holding "${ch.holding}" is not a drawing.${propHint(ch.holding, c, customProps)}`);
      for (const k of ["at", "out", "emoteAt"]) isAt(ch[k], sceneWords, `${w}.${k}`);
    });
    if (layout === "story") {
      const limit = humanLimit(s.bg), z = (x, fallback) => x.zIndex ?? fallback;
      chars.forEach((ch, j) => {
        const w = `${at}, characters[${j}]`;
        if (isAnimal(cast[ch.who])) {
          if (ch.size > SCALE.animal) W(w, `${ch.who} at size ${ch.size} will not fit in the frame; keep animals at ${SCALE.animal} or less. It looks huge next to a smaller actor.`);
        } else if (ch.size > limit) W(w, `${ch.who} at size ${ch.size} is out of scale for ${bgType(s.bg) ?? "this setting"} (${limit} at most). For a close-up, use camera.zoom and camera.focus: they scale the whole picture.`);
        // an emote is drawn in its actor's layer, so a prop in front hides it
        const emotes = ch.emote || (s.actions ?? []).some((a) => a.who === ch.who && a.emote);
        const cover = (s.props ?? []).find((p) => z(p, 4) > z(ch, 5) && (p.size ?? 0.3) >= 0.15 && p.x !== undefined && ch.x !== undefined && Math.abs(p.x - ch.x) < 0.2 && p.y > 0.5);
        if (emotes && cover) W(w, `${cover.name} (zIndex ${z(cover, 4)}) is in front of ${ch.who} (zIndex ${z(ch, 5)}) and will cover its emote and face. Use a lower zIndex unless it hides the actor on purpose.`);
      });
    }
    if (s.speaker && s.speaker !== "none" && !castIds.has(s.speaker) && !isProp(s.speaker)) E(`${at}, speaker`, `"${s.speaker}" is not a cast id, a prop or "none".`);
    // props / items
    (s.props ?? []).forEach((p, j) => {
      const w = `${at}, props[${j}]`;
      if (!p.name) E(w, `needs "name" (a drawing from the list)`);
      else if (!isProp(p.name)) E(`${w}.name`, `"${p.name}" is not a drawing.${propHint(p.name, c, customProps)} Or draw it as projects/<name>/props/${String(p.name).toLowerCase().replace(/\s+/g, "-")}.svg`);
      if (p.face && p.face !== true && !c.expressions.includes(p.face)) E(`${w}.face`, `"${p.face}" is not an expression.${hint(p.face, c.expressions)}`);
      if (p.motion && !c.motions.includes(p.motion)) E(`${w}.motion`, `"${p.motion}" does not exist.${hint(p.motion, c.motions)}`);
      if (p.enter && !c.enters.includes(p.enter)) E(`${w}.enter`, `"${p.enter}" does not exist.${hint(p.enter, c.enters)}`);
      if (p.label && p.label.split(/\s+/).length > 3) W(`${w}.label`, `"${p.label}" is ${p.label.split(/\s+/).length} words; labels read best at 1–3.`);
      for (const k of ["at", "out"]) isAt(p[k], sceneWords, `${w}.${k}`);
      (p.move ?? []).forEach((m, k) => { isAt(m.at, sceneWords, `${w}.move[${k}].at`); isAt(m.until, sceneWords, `${w}.move[${k}].until`); });
    });
    (s.items ?? []).forEach((it, j) => {
      const w = `${at}, items[${j}]`;
      if (it.image) { if (projectDir && !/^https?:/.test(it.image) && !existsSync(join(projectDir, it.image))) E(`${w}.image`, `file "${it.image}" is not in the project folder.`); }
      else if (!it.prop) E(w, `needs "prop" (a drawing) or "image"`);
      else if (!isProp(it.prop)) E(`${w}.prop`, `"${it.prop}" is not a drawing.${propHint(it.prop, c, customProps)}`);
      if (it.face && it.face !== true && !c.expressions.includes(it.face)) E(`${w}.face`, `"${it.face}" is not an expression.${hint(it.face, c.expressions)}`);
      isAt(it.at, sceneWords, `${w}.at`);
    });
    (s.texts ?? []).forEach((t, j) => {
      const w = `${at}, texts[${j}]`;
      if (!t.text) E(w, `needs "text"`);
      if (t.style && !c.textStyles.includes(t.style)) E(`${w}.style`, `"${t.style}" does not exist.${hint(t.style, c.textStyles)}`);
      for (const k of ["at", "out"]) isAt(t[k], sceneWords, `${w}.${k}`);
    });
    (s.actions ?? []).forEach((a, j) => {
      const w = `${at}, actions[${j}]`;
      if (a.at === undefined) E(w, `needs "at"`);
      isAt(a.at, sceneWords, `${w}.at`);
      if (a.who && !chars.some((ch) => ch.who === a.who)) E(w, `who "${a.who}" is not one of this scene's characters (${chars.map((ch) => ch.who).join(", ") || "none"}).`);
      if (a.pose && poseProblem(a.who, a.pose)) E(w, poseProblem(a.who, a.pose));
      if (a.holding && !isProp(a.holding)) E(w, `holding "${a.holding}" is not a drawing.${propHint(a.holding, c, customProps)}`);
      checkLook(a.look, `${w}.look`);
      if (a.expression && !c.expressions.includes(a.expression)) E(w, `expression "${a.expression}" does not exist.${hint(a.expression, c.expressions)}`);
      if (a.emote && !c.emotes.includes(a.emote)) E(w, `emote "${a.emote}" does not exist.${hint(a.emote, c.emotes)}`);
    });
    (s.sfx ?? []).forEach((x, j) => {
      if (!c.sfx.includes(x.name)) E(`${at}, sfx[${j}]`, `"${x.name}" is not a sound.${hint(x.name, c.sfx)}`);
      isAt(x.at, sceneWords, `${at}, sfx[${j}].at`);
    });
    for (const k of ["punch", "shake"]) (s.camera?.[k] ?? []).forEach((a, j) => isAt(a, sceneWords, `${at}, camera.${k}[${j}]`));
    if (s.bubble) {
      if (!s.bubble.text && !s.bubble.prop) E(`${at}, bubble`, `needs "text" or "prop"`);
      if (s.bubble.prop && !isProp(s.bubble.prop)) E(`${at}, bubble.prop`, `"${s.bubble.prop}" is not a drawing.${propHint(s.bubble.prop, c, customProps)}`);
      isAt(s.bubble.at, sceneWords, `${at}, bubble.at`);
    }
    if (s.number) { if (typeof s.number.value !== "number") E(`${at}, number.value`, "must be a number"); isAt(s.number.at, sceneWords, `${at}, number.at`); }
    if (s.image) { if (!s.image.src) E(`${at}, image`, `needs "src"`); else if (projectDir && !/^https?:/.test(s.image.src) && !existsSync(join(projectDir, s.image.src))) E(`${at}, image.src`, `file "${s.image.src}" is not in the project folder.`); }
    if (s.symbol && !c.symbols.includes(s.symbol)) E(`${at}, symbol`, `"${s.symbol}" is not one of ${c.symbols.join(" ")}`);
    // what each layout needs
    const nItems = (s.items ?? []).length;
    if (layout === "duo" && chars.length < 2) E(at, `layout "duo" needs 2 characters (has ${chars.length}).`);
    if ((layout === "compare" || layout === "transform") && nItems !== 2) E(at, `layout "${layout}" needs exactly 2 items (has ${nItems}).`);
    if (layout === "steps" && (nItems < 2 || nItems > 5)) E(at, `layout "steps" needs 2–5 items (has ${nItems}).`);
    if (layout === "title" && !s.title) E(at, `layout "title" needs "title" (≤ 4 words).`);
    if (layout === "number" && !s.number) E(at, `layout "number" needs "number": {"value": …}.`);
    if (layout === "image" && !s.image) E(at, `layout "image" needs "image": {"src": "file.png"}.`);
    if (layout === "name_card" && !s.title) E(at, `layout "name_card" needs "title" (the name).`);
    if (layout === "thought" && !s.bubble) W(at, `layout "thought" usually has "bubble": {"kind": "thought", "prop": …} or {"text": …}.`);
    if (["steps", "compare", "transform"].includes(layout) && (s.props ?? []).length) W(at, `layout "${layout}" shows "items"; its "props" are placed separately and may crowd the frame.`);
    if (!chars.length && !["title", "free", "news", "image"].includes(layout)) W(at, "has no characters; the reference style keeps the narrator on screen most of the time.");
    const things = (s.props ?? []).length + nItems + (s.texts ?? []).length;
    if (things > 6) W(at, `${things} things on screen; one idea per scene reads better.`);
    const nextStart = secondsOf(next?.start);
    if (Number.isFinite(start) && nextStart !== null && nextStart - start > 8) W(at, `lasts ${fmt(nextStart - start)} s; scenes over ~7 s feel slow. Split it at a sentence.`);
  });
  return { errors, warnings };
}

/** Validate a project's storyboard.json. Returns { errors, warnings, report }. */
export function validateProject(dir, { analysis, customProps } = {}) {
  const path = join(dir, "storyboard.json");
  let sb;
  try { sb = JSON.parse(readFileSync(path, "utf8")); }
  catch (e) {
    const m = String(e.message).match(/position (\d+)/);
    let where = "";
    if (m) { const src = readFileSync(path, "utf8"); const pos = +m[1]; const line = src.slice(0, pos).split("\n").length; where = ` (line ${line}: ${src.split("\n")[line - 1]?.trim().slice(0, 80)})`; }
    return { errors: [`storyboard.json is not valid JSON: ${e.message}${where}. Check commas and quotes.`], warnings: [], report: "" };
  }
  // the recordings decide who speaks and when, whatever the file says
  const timeline = loadTimeline(dir);
  if (timeline) sb.dialogue = timeline;
  const res = validateStoryboard(sb, { words: analysis?.words ?? [], voiced: analysis?.voiced ?? [], duration: analysis?.duration !== undefined ? videoDuration(sb, analysis) : undefined, projectDir: dir, customProps });
  const stale = dialogueStale(dir);
  if (stale) res.errors.unshift(`The recordings need assembling again (${stale}). Run: pnpm video plan ${basename(dir)}`);
  const report = [
    res.errors.length ? `✖ ${res.errors.length} error(s) — fix these:` : "✔ No errors.",
    ...res.errors.map((e, i) => `  ${i + 1}. ${e}`),
    ...(res.warnings.length ? [`⚠ ${res.warnings.length} warning(s) — judgement calls:`, ...res.warnings.map((w, i) => `  ${i + 1}. ${w}`)] : []),
  ].join("\n");
  return { ...res, report };
}
